lines = data.split('\n')[1:] # Skip header

for line in lines:
    if not line: continue
    # Match "POLYGON ((...))",Name
    match = re.search(r'"POLYGON \(\((.*?)\)\)",(.*)$', line)
    if not match:
        # Try without quotes for the last one
        match = re.search(r'POLYGON \(\((.*?)\)\),(.*)$', line)
        
    if match:
        coords_str = match.group(1)
        name = match.group(2).strip().strip(',')
        
        # Parse coordinates (lng lat, lng lat, ...)
        polygon = []
        pairs = coords_str.split(',')
        for pair in pairs:
            lng_lat = pair.strip().split(' ')
            if len(lng_lat) == 2:
                lng, lat = float(lng_lat[0]), float(lng_lat[1])
                polygon.append({'lat': lat, 'lng': lng})
        
        zone, created = CampusZone.objects.update_or_create(
            name=name,
            defaults={'polygon_coordinates': polygon}
        )
        print(f"{'Created' if created else 'Updated'} zone: {name}")

print("Done populating zones.")
